#!/usr/bin/env python3
"""Generate Sources/PasswordPieCore/PublicSuffixData.swift from the Public Suffix List.

Usage:
  curl -sSL https://publicsuffix.org/list/public_suffix_list.dat -o /tmp/psl.dat
  Scripts/gen_public_suffix.py /tmp/psl.dat [--out PATH]

Both the ICANN and the private sections are kept, so `alice.github.io` and `bob.github.io` are two sites.
Rules are written one per line, in punycode (IDN rules are converted label by label), with their `*.` and `!`
prefixes. The list is licensed MPL 2.0 (https://mozilla.org/MPL/2.0/).
"""
import argparse
import re


def to_ascii(rule):
    prefix = ""
    if rule.startswith("!"):
        prefix, rule = "!", rule[1:]
    labels = []
    for label in rule.split("."):
        if label == "*" or label.isascii():
            labels.append(label.lower())
        else:
            labels.append("xn--" + label.encode("punycode").decode("ascii"))
    return prefix + ".".join(labels)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("input")
    parser.add_argument("--out", default="Sources/PasswordPieCore/PublicSuffixData.swift")
    args = parser.parse_args()
    version = "unknown"
    rules = []
    seen = set()
    with open(args.input, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            match = re.match(r"^// VERSION: (.+)$", line)
            if match:
                version = match.group(1)
            if not line or line.startswith("//"):
                continue
            rule = to_ascii(line.split()[0])
            if rule not in seen:
                seen.add(rule)
                rules.append(rule)
    with open(args.out, "w", encoding="utf-8") as out:
        out.write("// Generated by Scripts/gen_public_suffix.py. Do not edit by hand.\n")
        out.write("// Source: the Public Suffix List (https://publicsuffix.org/), licensed MPL 2.0 (https://mozilla.org/MPL/2.0/).\n")
        out.write(f"// Version {version}, {len(rules)} rules, ICANN and private sections, IDN rules in punycode.\n")
        out.write('let bundledPublicSuffixRules = """\n')
        out.write("\n".join(rules))
        out.write('\n"""\n')


if __name__ == "__main__":
    main()
