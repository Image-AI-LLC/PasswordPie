#!/usr/bin/env python3
"""Generate Sources/PasswordPieCore/DomainRanksData.swift from a ranked domain list.

Usage:
  Scripts/gen_domain_ranks.py INPUT.csv [--limit 10000] [--out PATH]

INPUT.csv is a Majestic Million CSV (header has GlobalRank and Domain columns) or a plain
"rank,domain" CSV. The list must be ordered: Cloudflare Radar's 10k bucket is unordered
(only its top 100 carry exact ranks), so it cannot feed this table.

The output is one newline-joined string literal, one domain per line, rank = line number.
Parsing it lazily at first use stays fast; a 10,000-entry dictionary literal would make
the Swift type checker crawl, and SPM resources would not survive the hand-built .app.
"""
import argparse
import csv
import re
import sys

DOMAIN = re.compile(r"^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$")


def read_ranked(path, limit):
    rows = []
    with open(path, newline="", encoding="utf-8") as handle:
        reader = csv.reader(handle)
        header = [column.strip().lower() for column in next(reader)]
        if "domain" in header and "globalrank" in header:
            rank_at, domain_at = header.index("globalrank"), header.index("domain")
        elif len(header) >= 2 and header[0] == "rank":
            rank_at, domain_at = 0, 1
        else:
            sys.exit("Unrecognised header: expected GlobalRank,...,Domain or rank,domain")
        for row in reader:
            if len(row) <= max(rank_at, domain_at):
                continue
            domain = row[domain_at].strip().lower()
            if not DOMAIN.match(domain):
                continue  # skips IDN punycode oddities and junk rows
            try:
                rank = int(row[rank_at])
            except ValueError:
                continue  # skips a malformed rank cell, like a malformed domain
            rows.append((rank, domain))
            if len(rows) >= limit:
                break
    rows.sort()
    return [domain for _, domain in rows]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("input")
    parser.add_argument("--limit", type=int, default=10_000)
    parser.add_argument("--out", default="Sources/PasswordPieCore/DomainRanksData.swift")
    args = parser.parse_args()
    domains = read_ranked(args.input, args.limit)
    if len(domains) < 1000:
        sys.exit(f"Only {len(domains)} usable domains; refusing to write a tiny table.")
    body = "\n".join(domains)
    with open(args.out, "w", encoding="utf-8") as out:
        out.write("// Generated by Scripts/gen_domain_ranks.py. Do not edit by hand.\n")
        out.write("// Source: Majestic Million (https://majestic.com/reports/majestic-million),\n")
        out.write("// licensed CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/). Reduced to the top %d domains.\n" % len(domains))
        out.write("// One domain per line; the rank is the line number, starting at 1.\n")
        out.write('let bundledDomainRankText = """\n%s\n"""\n' % body)
    print(f"wrote {len(domains)} domains to {args.out}")


if __name__ == "__main__":
    main()
